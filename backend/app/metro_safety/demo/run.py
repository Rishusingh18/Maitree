"""Single-command end-to-end pipeline runner for AI Metro Platform Safety System.
Produces:
- Annotated output video with zones, bounding boxes, pose keypoints, event labels, severity banners, buzzer/alert indicators.
- JSON event log.
Usage:
python -m metro_safety.demo.run --video <path_or_keyword> --out-video <out.mp4> --out-log <events.json>
"""
from typing import List, Dict, Optional, Tuple
import argparse
from pathlib import Path
import json
import time
import numpy as np
import cv2

from metro_safety.config import load_config
from metro_safety.zones.geometry import ZoneManager
from metro_safety.perception.train_state import TrainState, SimulatedTrainStateProvider
from metro_safety.tracking.tracker import ByteTracker
from metro_safety.events.rule_classifier import RuleBasedEventClassifier
from metro_safety.events.learned_classifier import LearnedEventClassifier
from metro_safety.events.gesture import DistressGestureDetector
from metro_safety.escalation.engine import EscalationEngine
from metro_safety.perception.base import Detection
from metro_safety.events.models import SeverityLevel

COCO_PAIRS = [
    (0, 1), (0, 2), (1, 3), (2, 4),
    (5, 6), (5, 7), (7, 9), (6, 8), (8, 10),
    (5, 11), (6, 12), (11, 12),
    (11, 13), (13, 15), (12, 14), (14, 16)
]

def run_pipeline(
    video_source: str,
    output_video: Path | str = "demo_output.mp4",
    output_log: Path | str = "demo_events.json",
    train_state_val: str = "ABSENT",
    config_path: Optional[str] = None
):
    cfg = load_config(config_path)
    zm = ZoneManager(cfg["zones"])
    tracker = ByteTracker(
        track_high_thresh=cfg["tracking"].get("track_high_thresh", 0.22),
        track_low_thresh=cfg["tracking"].get("track_low_thresh", 0.12),
        new_track_thresh=cfg["tracking"].get("new_track_thresh", 0.18),
        track_buffer=cfg["tracking"].get("track_buffer", 30),
        match_thresh=cfg["tracking"].get("match_thresh", 0.6)
    )
    rule_clf = RuleBasedEventClassifier(
        line_crossing_thresh=cfg["events"]["line_crossing_consecutive_frames"],
        track_intrusion_thresh=cfg["events"]["track_intrusion_consecutive_frames"]
    )
    learned_clf = LearnedEventClassifier()
    gesture_det = DistressGestureDetector(
        min_persistence=cfg["gesture"]["min_persistence_frames"],
        use_macro_fallback=cfg["gesture"]["use_macro_fallback"]
    )
    escalation = EscalationEngine(
        station_id=cfg["system"]["station_id"],
        platform_id=cfg["system"]["platform_id"]
    )
    train_state = TrainState(train_state_val)

    # Resolve video source
    video_path = Path(video_source)
    if not video_path.exists():
        # Check standard demo clips
        alias_map = {
            "fall": "demo_clips/demo_fall.mp4",
            "jump": "demo_clips/demo_jump.mp4",
            "distress": "demo_clips/demo_distress.mp4",
            "synthetic": "demo_clips/demo_fall.mp4"
        }
        source_key = str(video_source).lower()
        if source_key in alias_map:
            video_path = Path(alias_map[source_key])
        else:
            raise FileNotFoundError(f"Requested video source not found and is not a recognized alias: {video_source}")

    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        raise RuntimeError(f"Cannot open video source: {video_path}")

    w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = cap.get(cv2.CAP_PROP_FPS) or 25.0

    out_v_path = Path(output_video)
    out_v_path.parent.mkdir(parents=True, exist_ok=True)
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    writer = cv2.VideoWriter(str(out_v_path), fourcc, fps, (w, h))

    # Initialize YOLO pose if available, fallback to mock detector
    pose_detector = None
    try:
        from metro_safety.perception.yolo_pose import YOLOPoseDetector
        pose_detector = YOLOPoseDetector(
            model_name=cfg["perception"]["model_name"],
            confidence_threshold=cfg["perception"]["confidence_threshold"],
            device=cfg["perception"]["device"]
        )
    except Exception as e:
        print(f"[Notice] YOLO pose not loaded ({e}), using synthetic detection tracker.")

    events_logged = []
    frame_idx = 0
    t_start = time.time()

    print(f"Processing video: {video_path} -> {out_v_path}...")

    while True:
        ret, frame = cap.read()
        if not ret:
            break

        timestamp = frame_idx / float(fps)

        # 1. Perception
        detections = []
        if pose_detector and pose_detector._model is not None:
            detections = pose_detector.detect(frame)
        else:
            # Synthetic / fallback keypoint detector via color thresholding of skeleton points
            # If detecting synthetic video generated by our simulator:
            # Search for skeleton orange joint circles (0, 180, 255)
            hsv = cv2.cvtColor(frame, cv2.COLOR_BGR2HSV)
            mask = cv2.inRange(hsv, np.array([10, 150, 150]), np.array([25, 255, 255]))
            contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
            pts = []
            for cnt in contours:
                if 2 <= cv2.contourArea(cnt) <= 120:
                    M = cv2.moments(cnt)
                    if M["m00"] > 0:
                        pts.append([M["m10"] / M["m00"], M["m01"] / M["m00"], 0.9])
            if len(pts) >= 6:
                pts_arr = np.array(pts)
                x1, y1 = np.min(pts_arr[:, 0]) - 15, np.min(pts_arr[:, 1]) - 20
                x2, y2 = np.max(pts_arr[:, 0]) + 15, np.max(pts_arr[:, 1]) + 15
                box = np.array([x1, y1, x2, y2], dtype=np.float32)
                # Fit 17 keypoints with anatomically preserved joint identity
                kpts = np.zeros((17, 3), dtype=np.float32)
                sorted_by_y = pts_arr[np.argsort(pts_arr[:, 1])]
                cx = float(np.mean(pts_arr[:, 0]))
                cy = float(np.mean(pts_arr[:, 1]))
                top_y = float(sorted_by_y[0][1])
                bottom_y = float(sorted_by_y[-1][1])
                h_est = max(bottom_y - top_y, 30.0)

                kpts[0] = [cx, top_y + 0.08 * h_est, 0.95]        # nose
                kpts[1] = [cx - 4, top_y + 0.06 * h_est, 0.9]      # L eye
                kpts[2] = [cx + 4, top_y + 0.06 * h_est, 0.9]      # R eye
                kpts[3] = [cx - 8, top_y + 0.08 * h_est, 0.85]     # L ear
                kpts[4] = [cx + 8, top_y + 0.08 * h_est, 0.85]     # R ear
                sh_y = top_y + 0.22 * h_est
                kpts[5] = [cx - 14, sh_y, 0.92]                    # L shoulder
                kpts[6] = [cx + 14, sh_y, 0.92]                    # R shoulder
                hip_y = top_y + 0.52 * h_est
                kpts[11] = [cx - 10, hip_y, 0.9]                   # L hip
                kpts[12] = [cx + 10, hip_y, 0.9]                   # R hip
                knee_y = top_y + 0.75 * h_est
                kpts[13] = [cx - 8, knee_y, 0.9]                   # L knee
                kpts[14] = [cx + 8, knee_y, 0.9]                   # R knee
                kpts[15] = [cx - 8, bottom_y, 0.9]                 # L ankle
                kpts[16] = [cx + 8, bottom_y, 0.9]                 # R ankle

                # Wrists / elbows: detect raised hands (points above shoulder/nose)
                raised_pts = [p for p in sorted_by_y if p[1] < sh_y]
                if len(raised_pts) >= 2:
                    kpts[7] = [cx - 15, (sh_y + top_y) / 2, 0.9]   # L elbow
                    kpts[8] = [cx + 15, (sh_y + top_y) / 2, 0.9]   # R elbow
                    kpts[9] = [raised_pts[0][0], raised_pts[0][1], 0.95]  # L wrist
                    kpts[10] = [raised_pts[1][0], raised_pts[1][1], 0.95] # R wrist
                elif len(raised_pts) == 1:
                    kpts[7] = [cx - 15, (sh_y + top_y) / 2, 0.9]
                    kpts[8] = [cx + 14, (sh_y + hip_y) / 2, 0.9]
                    kpts[9] = [raised_pts[0][0], raised_pts[0][1], 0.95]
                    kpts[10] = [cx + 14, hip_y + 5, 0.9]
                else:
                    kpts[7] = [cx - 14, (sh_y + hip_y) / 2, 0.9]
                    kpts[8] = [cx + 14, (sh_y + hip_y) / 2, 0.9]
                    kpts[9] = [cx - 14, hip_y + 5, 0.9]
                    kpts[10] = [cx + 14, hip_y + 5, 0.9]

                detections = [Detection(box=box, confidence=0.92, keypoints=kpts)]

        # 2. Tracking
        tracked_dets = tracker.update(detections)

        # 3. Behavior Events & Gestures
        rule_evs = rule_clf.process_frame(frame_idx, timestamp, tracked_dets, zm, train_state)
        gest_evs = gesture_det.process_frame(frame_idx, timestamp, tracked_dets, zm, train_state)
        all_evs = rule_evs + gest_evs

        # Per-frame escalation lifecycle: clear confirmed resolved tracks (present in safe platform with no active hazards)
        active_hazard_tracks = {ev.track_id for ev in all_evs if hasattr(ev, 'track_id')}
        for det in tracked_dets:
            if det.track_id is not None and det.track_id not in active_hazard_tracks:
                if zm.get_zone_for_point(det.foot_anchor) == "platform":
                    escalation.clear_track(det.track_id)

        # 4. Escalation: Select displayed decision by explicit severity priority (L3 > L2 > L1 > DISTRESS > NORMAL)
        SEVERITY_PRIORITY = {
            SeverityLevel.L3: 4,
            SeverityLevel.L2: 3,
            SeverityLevel.L1: 2,
            SeverityLevel.DISTRESS: 1,
            SeverityLevel.NORMAL: 0
        }
        current_decision = None
        for ev in all_evs:
            dec = escalation.evaluate(ev, current_time=timestamp)
            if current_decision is None or SEVERITY_PRIORITY.get(dec.severity, 0) > SEVERITY_PRIORITY.get(current_decision.severity, 0):
                current_decision = dec
            events_logged.append({
                "frame": frame_idx,
                "timestamp": round(timestamp, 3),
                "event": ev.to_dict(),
                "severity": dec.severity.value,
                "action": dec.action_taken,
                "buzzer_active": dec.buzzer_active,
                "ets_triggered": dec.ets_triggered
            })

        # 5. Visual Annotation
        annotated = zm.draw_zones(frame, alpha=0.25)

        # Draw Person & Skeleton
        for det in tracked_dets:
            bx = det.box.astype(int)
            tid = det.track_id or 0
            foot = det.foot_anchor
            zone_name = zm.get_zone_for_point(foot)

            # Bounding box & ID
            cv2.rectangle(annotated, (bx[0], bx[1]), (bx[2], bx[3]), (0, 255, 0), 2)
            cv2.putText(annotated, f"ID:{tid} [{zone_name}]", (bx[0], max(15, bx[1] - 8)),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 2)
            # Anchor point
            cv2.circle(annotated, (int(foot[0]), int(foot[1])), 5, (0, 0, 255), -1)

            # Keypoints skeleton if present
            if det.keypoints is not None:
                for p1_i, p2_i in COCO_PAIRS:
                    p1 = det.keypoints[p1_i]
                    p2 = det.keypoints[p2_i]
                    if p1[2] > 0.4 and p2[2] > 0.4:
                        cv2.line(annotated, (int(p1[0]), int(p1[1])), (int(p2[0]), int(p2[1])), (255, 255, 0), 1)

        # Severity Alert Banner
        banner_h = 60
        top_banner = np.zeros((banner_h, w, 3), dtype=np.uint8)

        sev = current_decision.severity if current_decision else SeverityLevel.NORMAL
        if sev == SeverityLevel.L3:
            banner_color = (0, 0, 220)      # Bright Red
            status_text = "LEVEL 3 EMERGENCY: TRAIN STOP RECOMMENDED / ETS TRIPPED"
        elif sev == SeverityLevel.L2:
            banner_color = (0, 140, 255)    # Orange
            status_text = "LEVEL 2 ALERT: PERSON ON TRACK BED (BUZZER + CONTROL ROOM)"
        elif sev == SeverityLevel.L1:
            banner_color = (0, 220, 240)    # Yellow
            status_text = "LEVEL 1 WARNING: YELLOW LINE CROSSED (PLATFORM BUZZER)"
        elif sev == SeverityLevel.DISTRESS:
            banner_color = (180, 0, 180)    # Purple
            status_text = "SILENT DISTRESS SIGNAL DETECTED: DISPATCHING SECURITY"
        else:
            banner_color = (30, 140, 30)    # Green
            status_text = f"PLATFORM SECURE | TRAIN: {train_state.value}"

        cv2.rectangle(annotated, (0, 0), (w, banner_h), banner_color, -1)
        cv2.putText(annotated, status_text, (15, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (255, 255, 255), 2)

        # Hardware Indicators (Buzzer & ETS)
        buzzer_on = escalation.buzzer.is_active(escalation.platform_id)
        ets_on = escalation.trip_switch.is_tripped()

        b_color = (0, 0, 255) if buzzer_on else (100, 100, 100)
        e_color = (0, 0, 255) if ets_on else (100, 100, 100)
        cv2.circle(annotated, (w - 140, 48), 6, b_color, -1)
        cv2.putText(annotated, "BUZZER", (w - 128, 52), cv2.FONT_HERSHEY_SIMPLEX, 0.4, (255, 255, 255), 1)
        cv2.circle(annotated, (w - 60, 48), 6, e_color, -1)
        cv2.putText(annotated, "ETS", (w - 48, 52), cv2.FONT_HERSHEY_SIMPLEX, 0.4, (255, 255, 255), 1)

        # Time & FPS
        cv2.putText(annotated, f"TIME: {timestamp:.2f}s | CAM: {cfg['system']['camera_id']}",
                    (15, 52), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (220, 220, 220), 1)

        writer.write(annotated)
        frame_idx += 1

    cap.release()
    writer.release()

    # Save Event Log
    out_log_path = Path(output_log)
    out_log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_log_path, "w", encoding="utf-8") as f:
        json.dump({
            "video_source": str(video_path),
            "frames_processed": frame_idx,
            "total_events": len(events_logged),
            "events": events_logged
        }, f, indent=2)

    print(f"Finished pipeline. Output video: {out_v_path}, Log: {out_log_path}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="AI Metro Platform Safety System CLI")
    parser.add_argument("--video", type=str, default="demo_clips/demo_fall.mp4", help="Video path or alias (fall/jump/distress)")
    parser.add_argument("--out-video", type=str, default="demo_output.mp4", help="Annotated video output path")
    parser.add_argument("--out-log", type=str, default="demo_events.json", help="JSON events output path")
    parser.add_argument("--train-state", type=str, default="ABSENT", help="Train state: ABSENT, APPROACHING, PRESENT")
    parser.add_argument("--config", type=str, default=None, help="Config YAML path")
    args = parser.parse_args()

    run_pipeline(args.video, args.out_video, args.out_log, args.train_state, args.config)
